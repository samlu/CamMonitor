export function normalizeChineseLocale(tag) {
  if (!tag || typeof tag !== "string") return "zh-Hans";
  const lower = tag.toLowerCase();
  if (lower.includes("hant") || /-tw\b|-hk\b|-mo\b/.test(lower)) {
    return "zh-Hant";
  }
  return "zh-Hans";
}

export function resolveLocale(preferred, browserLanguages = globalThis.navigator?.languages || [globalThis.navigator?.language || "en"]) {
  if (preferred && SUPPORTED_LOCALES.includes(preferred)) {
    return preferred;
  }
  const langs = Array.isArray(browserLanguages) ? browserLanguages : [browserLanguages];
  for (const raw of langs) {
    if (!raw || typeof raw !== "string") continue;
    const lower = raw.toLowerCase();
    if (lower.startsWith("zh")) return normalizeChineseLocale(lower);
    if (lower.startsWith("ja")) return "ja";
    if (lower.startsWith("en")) return "en";
  }
  return "en";
}

export function createTranslator(locale) {
  const resolved = SUPPORTED_LOCALES.includes(locale) ? locale : "en";
  const dict = TRANSLATIONS[resolved] || TRANSLATIONS.en;
  return function t(key, vars = {}) {
    const template = dict[key] ?? TRANSLATIONS.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
  };
}
